#!/usr/bin/env python3
"""Secrets for the roadtrip stack: encrypted in git, mounted as files at runtime.

Everything lives in this directory:

    registry.yaml       which secrets exist, who gets them, where they're required
    common.enc.env      values shared by every environment
    local.enc.env       overlay for `tilt up` / `make run`
    prod.enc.env        overlay for `make run env=prod`
    .sops.yaml          age recipients
    manage.py           this tool

A vault is a dotenv whose *values* are age-encrypted and whose *keys* are
plaintext, so `git diff` shows which secret changed without showing what it
changed to. All of it is committed: durability is git history, and deploying a
secret is the same `git pull` that deploys code.

Nothing is ever decrypted to a file. `exec` merges common + the environment's
overlay in memory and replaces itself with the target command; Docker Compose
then turns those environment values into /run/secrets/<name> file mounts, so
containers read files and the values never appear in `docker inspect` or the
host process table.

    ./secrets/manage.py exec prod -- docker compose up -d

Environments mirror application-{local,prod}.yaml, so one word selects both the
app profile and its secrets.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

SECRETS_DIR = Path(__file__).resolve().parent
ROOT = SECRETS_DIR.parent

REGISTRY_FILE = SECRETS_DIR / "registry.yaml"
SOPS_CONFIG = SECRETS_DIR / ".sops.yaml"
GENERATED_COMPOSE = ROOT / "docker-compose.secrets.yml"

COMMON_ENV = "common"
ENVIRONMENTS = ("local", "prod")

# Consumers that are Compose services and receive a mounted file. `host-tools`
# runs outside containers, so those get environment injection from `exec`
# instead — there is nowhere to mount a file.
SERVICE_CONSUMERS = ("postgres", "backend", "grafana", "cloudflared")

GENERATED_HEADER = "# GENERATED by secrets/manage.py — do not edit."

# One key path on every host, macOS and Linux alike. sops would otherwise
# resolve this with Go's os.UserConfigDir(), which differs per platform and
# makes runbooks stop being copy-pasteable. run_sops passes it explicitly.
AGE_KEY_FILE = Path(
    os.environ.get(
        "SOPS_AGE_KEY_FILE", Path.home() / ".config" / "sops" / "age" / "keys.txt"
    )
)

ADOPTABLE_AGE_KEY_FILES = [
    path
    for path in (
        Path.home() / "Library" / "Application Support" / "sops" / "age" / "keys.txt",
        Path.home() / ".config" / "sops" / "age" / "keys.txt",
    )
    if path != AGE_KEY_FILE
]

SOPS_FORMAT_ARGS = ["--input-type", "dotenv", "--output-type", "dotenv"]

# age-keygen writes the public half as a comment beside the private key.
AGE_PUBLIC_KEY_COMMENT = "# public key:"

# An age public key is bech32: "age1" plus 58 characters of bech32's alphabet,
# which omits 1, b, i and o. Checking the shape before it reaches .sops.yaml
# turns a truncated paste into an error now, rather than a vault that re-wraps
# cleanly and still cannot be opened by the machine it was meant to enroll.
AGE_PUBLIC_KEY_RE = re.compile(r"age1[02-9ac-hj-np-z]{58}")

# Where recipients live in .sops.yaml. Each is a list item under `- age:`,
# preceded by a comment naming its holder.
AGE_BLOCK_RE = re.compile(r"^(\s*)-\s+age:\s*$")
RECIPIENT_RE = re.compile(r"^(\s*)-\s+(age1[02-9ac-hj-np-z]+)\s*$")
# Indent of a recipient relative to the `- age:` line: past the "- ", then one
# nesting level in. Only used when the block is empty and has no line to copy.
AGE_BLOCK_ITEM_INDENT = " " * 4

PRIVATE_KEY_WARNING = (
    "The private half is not in the repo and cannot be recovered. Back it up."
)

# sops exits 200 from `edit` when the editor closed without changing anything.
# An outcome, not a failure.
SOPS_EXIT_NO_CHANGE = 200
SOPS_METADATA_PREFIX = "sops_"

AGE_KEY_FILE_MODE = 0o600


class SecretsError(RuntimeError):
    """A failure whose message is already written for a human."""


# --------------------------------------------------------------------------
# registry
#
# Parsed with the standard library only: PyYAML is not installed anywhere in
# this repo (the one script that imports it cannot even load), and a secrets
# tool that fails to start because of a missing dependency is worse than a
# small parser. The file is still valid YAML — the Kotlin side reads it with
# Ktor's real parser — so this handles exactly the shape `add` writes:
# top-level NAME:, two-space-indented `key: value`, and `[a, b]` inline lists.
# Anything outside that shape raises rather than being silently misread.
# --------------------------------------------------------------------------

ENTRY_RE = re.compile(r"^([A-Z][A-Z0-9_]*):\s*$")
FIELD_RE = re.compile(r"^  ([a-z_]+):\s*(.*)$")


class Secret:
    def __init__(self, name: str, description: str, consumers: list[str],
                 required_in: list[str]):
        self.name = name
        self.description = description
        self.consumers = consumers
        self.required_in = required_in

    @property
    def file_name(self) -> str:
        """Compose secret name and the basename under /run/secrets."""
        return self.name.lower()

    def services(self) -> list[str]:
        """Compose services that should receive this as a mounted file."""
        return [c for c in self.consumers if c in SERVICE_CONSUMERS]


def parse_registry(text: str) -> dict[str, Secret]:
    secrets: dict[str, Secret] = {}
    name: str | None = None
    fields: dict[str, object] = {}

    def flush() -> None:
        if name is None:
            return
        missing = {"description", "consumers", "required_in"} - fields.keys()
        if missing:
            raise SecretsError(f"{name} in registry.yaml is missing: {', '.join(sorted(missing))}")
        secrets[name] = Secret(
            name=name,
            description=str(fields["description"]),
            consumers=list(fields["consumers"]),  # type: ignore[arg-type]
            required_in=list(fields["required_in"]),  # type: ignore[arg-type]
        )

    for raw in text.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        entry = ENTRY_RE.match(raw)
        if entry:
            flush()
            name, fields = entry.group(1), {}
            continue
        field = FIELD_RE.match(raw)
        if field and name is not None:
            key, value = field.group(1), field.group(2).strip()
            if value.startswith("[") and value.endswith("]"):
                inner = value[1:-1].strip()
                fields[key] = [v.strip() for v in inner.split(",") if v.strip()]
            elif value in {"true", "false"}:
                fields[key] = value == "true"
            else:
                fields[key] = value
            continue
        raise SecretsError(f"registry.yaml: cannot parse line: {raw!r}")
    flush()
    if not secrets:
        raise SecretsError("registry.yaml declares no secrets")
    return secrets


def load_registry() -> dict[str, Secret]:
    if not REGISTRY_FILE.exists():
        raise SecretsError(f"{REGISTRY_FILE.relative_to(ROOT)} is missing")
    return parse_registry(REGISTRY_FILE.read_text())


# --------------------------------------------------------------------------
# dotenv
#
# Deliberately dumb: split on the first `=`, keep the remainder verbatim.
# Cookie headers and connection strings contain `=`, `;` and quotes, and the
# consumer sees the raw value, so any "helpful" unquoting would corrupt it.
# --------------------------------------------------------------------------


def parse_dotenv(text: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, value = stripped.partition("=")
        key = key.strip()
        if key and not key.startswith(SOPS_METADATA_PREFIX):
            values[key] = value
    return values


