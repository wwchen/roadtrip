# sops
# --------------------------------------------------------------------------


def require_tools(*names: str) -> None:
    missing = [n for n in names if shutil.which(n) is None]
    if missing:
        raise SecretsError(
            f"missing required tool(s): {', '.join(missing)}\n"
            f"Install with: brew install {' '.join(missing)}"
        )


def misplaced_age_key() -> Path | None:
    if AGE_KEY_FILE.exists():
        return None
    return next((p for p in ADOPTABLE_AGE_KEY_FILES if p.exists()), None)


def run_sops(args: list[str], *, capture: bool = True, stdin: str | None = None,
             allow: tuple[int, ...] = ()) -> tuple[int, str]:
    require_tools("sops")
    env = {**os.environ, "SOPS_AGE_KEY_FILE": str(AGE_KEY_FILE)}
    proc = subprocess.run(
        ["sops", *args],
        cwd=SECRETS_DIR,
        input=stdin,
        capture_output=capture,
        text=True,
        env=env,
    )
    if proc.returncode != 0 and proc.returncode not in allow:
        detail = (proc.stderr or proc.stdout or "").strip() if capture else ""
        # sops' "did not find keys in locations ..." lists only environment
        # variables, so a key in the wrong directory reads as no key at all.
        stranded = misplaced_age_key()
        hint = (
            f"\n\nhint: an age identity exists at {stranded}, but this repo keeps it at"
            f"\n      {AGE_KEY_FILE}. Adopt it with: ./secrets/manage.py enroll"
            if stranded
            else ""
        )
        raise SecretsError(f"sops failed ({' '.join(args)})\n{detail}{hint}")
    return proc.returncode, (proc.stdout if capture else "")


def vault_path(env_name: str) -> Path:
    return SECRETS_DIR / f"{env_name}.enc.env"


def read_vault(env_name: str) -> dict[str, str]:
    path = vault_path(env_name)
    if not path.exists():
        raise SecretsError(
            f"{path.relative_to(ROOT)} does not exist.\n"
            "First-time setup: ./secrets/manage.py enroll, then ./secrets/manage.py import"
        )
    _, plaintext = run_sops(["--decrypt", *SOPS_FORMAT_ARGS, path.name])
    return parse_dotenv(plaintext)


def write_vault(env_name: str, values: dict[str, str]) -> None:
    """Encrypt values into a vault via stdin, so no plaintext reaches disk."""
    path = vault_path(env_name)
    body = "".join(f"{k}={v}\n" for k, v in sorted(values.items()))
    # An empty vault still has to be a valid encrypted file; give it a comment
    # to carry the sops metadata.
    if not body:
        body = "# (no values for this environment)\n"
    _, ciphertext = run_sops(
        ["--encrypt", *SOPS_FORMAT_ARGS, "--filename-override", path.name, "/dev/stdin"],
        stdin=body,
    )
    path.write_text(ciphertext)


def load_merged(env_name: str) -> dict[str, str]:
    """Every registered secret, with common + the environment's overlay applied.

    Registered-but-unset secrets are exported as empty strings rather than
    omitted. Compose refuses to start when an `environment:`-sourced secret's
    variable is unset, so omitting them would make registering a secret you
    have not filled in yet break the whole stack. Empty is also the state the
    application already understands: ConfigSection maps "" to null and
    SecretsBootstrap counts blank as missing, so an unset optional secret
    disables its feature exactly as before.
    """
    if env_name not in ENVIRONMENTS:
        raise SecretsError(
            f"unknown environment '{env_name}'. Expected one of: {', '.join(ENVIRONMENTS)}"
        )
    merged = {name: "" for name in load_registry()}
    merged.update(read_vault(COMMON_ENV))
    merged.update({k: v for k, v in read_vault(env_name).items() if v})
    return merged


# --------------------------------------------------------------------------
# generation — this is what makes `consumers` enforceable rather than decorative
# --------------------------------------------------------------------------


def render_compose(registry: dict[str, Secret]) -> str:
    """Render docker-compose.secrets.yml from the registry.

    Compose sources each secret from an environment variable, which `exec`
    supplies in memory, and mounts it at /run/secrets/<name>. So the value is
    a file inside the container and never a container environment variable.
    """
    by_service: dict[str, list[Secret]] = {}
    for secret in registry.values():
        for service in secret.services():
            by_service.setdefault(service, []).append(secret)

    lines = [
        GENERATED_HEADER,
        "#",
        "# Source: secrets/registry.yaml (the `consumers` field).",
        "# Regenerate: ./secrets/manage.py generate",
        "#",
        "# Compose is invoked with `-f docker-compose.yml -f docker-compose.secrets.yml`.",
        "# Because this file is what actually runs, a wrong `consumers` entry means the",
        "# container genuinely does not get the secret — the registry cannot drift from",
        "# reality without something breaking loudly.",
        "",
        "services:",
    ]
    for service in sorted(by_service):
        lines.append(f"  {service}:")
        lines.append("    secrets:")
        for secret in sorted(by_service[service], key=lambda s: s.name):
            lines.append(f"      - {secret.file_name}")
    lines.append("")
    lines.append("secrets:")
    for secret in sorted(
        {s.name: s for svc in by_service.values() for s in svc}.values(),
        key=lambda s: s.name,
    ):
        lines.append(f"  {secret.file_name}:")
        lines.append(f"    environment: {secret.name}")
    return "\n".join(lines) + "\n"


def cmd_generate(args: argparse.Namespace) -> int:
    rendered = render_compose(load_registry())
    current = GENERATED_COMPOSE.read_text() if GENERATED_COMPOSE.exists() else ""
    if args.check:
        if current != rendered:
            print(
                f"error: {GENERATED_COMPOSE.name} is stale. "
                "Run: ./secrets/manage.py generate",
                file=sys.stderr,
            )
            return 1
        print(f"{GENERATED_COMPOSE.name} is up to date")
        return 0
    if current == rendered:
        print(f"{GENERATED_COMPOSE.name} already current")
        return 0
    GENERATED_COMPOSE.write_text(rendered)
    print(f"wrote {GENERATED_COMPOSE.name}")
    return 0


